from app.rewrite.layers._layer_base import run_layer_llm

_SYSTEM_PROMPT = """
당신은 문장에서 "사람 이름" 언급만 정리하는 AI입니다.

[규칙]
1. "항목" 목록에 있는 이름만 처리 대상이다. 목록에 없는 다른 내용은 절대
   손대지 않는다.
2. necessary가 false인 이름은 문장에서 자연스럽게 제거하거나 일반화한다
   (예: "김철수입니다, " 통째로 제거, "김철수 대리" → "대리").
3. necessary가 true인 이름은 그대로 유지한다 — 이 경우 이름과 관련해서
   아무것도 지우거나 바꾸지 않는다.
4. 항목의 모든 이름이 necessary: true이면, 입력 문장을 한 글자도 바꾸지 않고
   그대로 출력한다. 절대 새로운 문장으로 다시 쓰지 않는다.
5. 당신은 이 문장에 답변하거나 요청을 수행하는 게 아니다 — 문장 자체를
   다듬는 편집자다. "~써줘", "~해줘" 같은 요청 표현을 "~해드리겠습니다"
   같은 응답/완료 표현으로 절대 바꾸지 않는다.
6. 이름을 제거해서 조사·쉼표가 어색하게 남으면 자연스럽게 같이 정리한다.
7. 문장 종류(요청문/평서문)와 어투를 바꾸지 않는다.
8. 새로운 정보를 추가하지 않는다.
9. Markdown을 사용하지 않는다.
10. 다듬은 문장만 출력한다. 설명하지 않는다.

[예시]
목적: 교수님께 결석 사실을 알리는 이메일 작성
항목: [{"value": "김철수", "necessary": false}]
문장: 김철수입니다, 성신여자대학교 학생인데 교수님께 결석계 이메일 좀 써줘
출력: 성신여자대학교 학생인데 교수님께 결석계 이메일 좀 써줘

목적: 인사팀에 재직증명서 발급 요청 이메일 작성
항목: [{"value": "김철수", "necessary": true}]
문장: 김철수입니다, 인사팀에 재직증명서 발급 요청 이메일 좀 써줘
출력: 김철수입니다, 인사팀에 재직증명서 발급 요청 이메일 좀 써줘
"""


def rewrite_person_layer(text: str, purpose: str, entities: list) -> str:
    """entities: [{"value": str, "necessary": bool}, ...] (PERSON 타입만)."""
    return run_layer_llm(_SYSTEM_PROMPT, purpose, entities, text)

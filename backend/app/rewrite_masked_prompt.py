import re
import ollama


SYSTEM_PROMPT = """
당신은 문장에서 비식별화 안내 문구를 제거하고 자연스럽게 다듬는 AI입니다.

[규칙]
1. 입력 문장의 의미를 절대 바꾸지 않는다.
2. 문장 종류를 바꾸지 않는다.
   - 요청문은 요청문으로 유지한다.
   - 평서문은 평서문으로 유지한다.
3. 어투를 바꾸지 않는다.
   - 구어체는 구어체로 유지한다.
   - "~인데" 를 "~이시군요" 로 바꾸지 않는다.
4. (연락처 비식별화), (이메일 비식별화), (비식별화) 같은
   안내 문구와 그 앞 항목명(이메일, 계좌번호 등)을
   문장에서 완전히 제거한다.
   예) "이메일은 (이메일 비식별화)이고" → 통째로 제거
   예) "계좌번호는 (비식별화)인데" → 통째로 제거
   예) "(연락처 비식별화)로 담당자한테" → "(연락처 비식별화)로" 만 제거
5. 숫자+별표/X 형태의 마스킹 값(900101-1******, 1234-XXXX-XXXX-3456 등)은
   그대로 유지한다.
6. 요청 표현은 아래 기준으로만 통일한다.
   "써줘", "써라", "만들어줘" → "작성해줘"
   "해줘", "해라", "해봐" → "해줘"
7. 새로운 정보를 추가하지 않는다.
8. Markdown을 사용하지 않는다.
9. 다듬은 문장만 출력한다.

[예시]
입력: OO회사 인턴입니다. 이메일은 (이메일 비식별화)이고 계좌번호는 (비식별화)인데, 인사팀에 급여 문의 이메일 써줘
출력: OO회사 인턴입니다. 인사팀에 급여 문의 이메일 작성해줘

입력: OO기관 소속인데, (연락처 비식별화)로 담당자한테 환불 신청 문자 메시지 써줘
출력: OO기관 소속인데, 담당자한테 환불 신청 문자 메시지 작성해줘

입력: OO대학교 학생인데, 교수님한테 (이메일 비식별화)로 과제 연장 부탁하는 이메일 써줘
출력: OO대학교 학생인데, 교수님한테 과제 연장 부탁하는 이메일 작성해줘

입력: 오늘 병원 가야해서 (연락처 비식별화)로 팀장님한테 반차 쓴다고 문자 메시지 써줘
출력: 오늘 병원 가야해서 팀장님한테 반차 쓴다고 문자 메시지 작성해줘

입력: 서울특별시 강남구 살고 있고, 주민번호는 900101-1******이야, 개인정보 처리 동의서 내용 정리해줘
출력: 서울특별시 강남구 살고 있고, 주민번호는 900101-1******이야, 개인정보 처리 동의서 내용 정리해줘
"""


# =====================================
# 마스킹 기호 전처리 패턴
# =====================================

# 별표 있는 이름: 이**, 최유**, 홍길동**
_NAME_MASKED_PATTERN = re.compile(
    r"[가-힣]+\*+"
    r"(이고|이며|이라|이랑|이나|이은|이는|인데|이가|이를"
    r"|이에|이로|이야|이에요|입니다|이었|이던)?"
)

# 이름 제거 후 남는 도입부 잔재
_INTRO_PATTERN = re.compile(
    r"(나는|저는|저|나)\s*(,|이고|이며|이랑|인데)?\s*"
)

# 전화번호: 010-23**-****
_PHONE_PATTERN = re.compile(r"\d{2,4}-\d{2,4}\*+-\*+")

# 이메일
_EMAIL_PATTERN = re.compile(
    r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}"
)

# 비식별화 안내 문구 + 앞 항목명 + 뒤 조사 통째로 제거
# 예) "이메일은 (이메일 비식별화)이고" → 제거
# 예) "계좌번호는 (비식별화)인데" → 제거
_PII_LABEL_PATTERN = re.compile(
    r"[가-힣A-Za-z0-9]+[은는이가을를도]?\s*"
    r"\([^)]*비식별화[^)]*\)"
    r"[이가을를은는]?\s*"
    r"(이고|이며|이라|인데|이야|입니다|이었)?"
    r"[,\s]*"
)

# 잔여 안내 문구 제거 (앞 항목명 없이 남은 경우)
_PII_RESIDUAL_PATTERN = re.compile(
    r"\([^)]*비식별화[^)]*\)[이가을를은는로]?\s*"
    r"(이고|이며|이라|인데|이야|입니다)?"
    r"[,\s]*"
)


def _remove_masked_symbols(text: str, mask_info: list) -> str:
    """
    마스킹 기호를 처리한다.
    - 이름: 제거
    - 전화번호/이메일: 안내 문구로 교체 후 안내 문구 자체도 제거
    - 주민번호/계좌/카드 등 숫자+별표: 그대로 유지
    """

    # =====================================
    # 1. 마스킹 안 된 이름 제거
    #    mask_info의 original 값으로 직접 찾아 제거
    # =====================================
    for item in mask_info:

        if item.get("type") == "PERSON":

            original = item.get("original", "")

            if original and original in text:

                text = re.sub(
                    re.escape(original)
                    + r"(이고|이며|이라|이랑|이나|이은|이는|인데"
                    r"|이가|이를|이에|이로|이야|이에요|입니다|이었|이던)?",
                    "",
                    text
                )

    # =====================================
    # 2. 별표 있는 이름 + 조사/접속어 제거
    # =====================================
    text = _NAME_MASKED_PATTERN.sub("", text)

    # =====================================
    # 3. 이름 제거 후 남는 도입부 잔재 제거
    # =====================================
    text = _INTRO_PATTERN.sub("", text)

    # =====================================
    # 4. 전화번호 → 안내 문구로 교체
    # =====================================
    text = _PHONE_PATTERN.sub("(연락처 비식별화)", text)

    # =====================================
    # 5. 이메일 → 안내 문구로 교체
    # =====================================
    text = _EMAIL_PATTERN.sub("(이메일 비식별화)", text)

    # =====================================
    # 6. 비식별화 안내 문구 + 앞 항목명 통째로 제거
    #    예) "이메일은 (이메일 비식별화)이고" → 제거
    #    예) "계좌번호는 (비식별화)인데" → 제거
    # =====================================
    text = _PII_LABEL_PATTERN.sub("", text)

    # =====================================
    # 7. 잔여 안내 문구 제거
    # =====================================
    text = _PII_RESIDUAL_PATTERN.sub("", text)

    # =====================================
    # 8. 숫자+별표/XXXX 형태는 그대로 유지
    #    예) 900101-1****** → 그대로
    #        1234-XXXX-XXXX-3456 → 그대로
    # =====================================

    # =====================================
    # 9. 남은 별표 제거 (이름 마스킹 잔재)
    # =====================================
    text = re.sub(r"\*+", "", text)

    # =====================================
    # 10. 문장 앞 쉼표/공백 정리
    # =====================================
    text = re.sub(r"^\s*[,，]\s*", "", text)

    # =====================================
    # 11. 연속 공백 정리
    # =====================================
    text = re.sub(r" {2,}", " ", text)

    # =====================================
    # 12. 빈 괄호 제거
    # =====================================
    text = re.sub(r"\( *\)", "", text)

    return text.strip()


def _strip_markdown_fence(text: str) -> str:

    text = text.strip()

    if text.startswith("```"):

        lines = text.split("\n")

        if lines[0].startswith("```"):
            lines = lines[1:]

        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]

        text = "\n".join(lines).strip()

    return text


def rewrite_masked_prompt(masked_text, mask_info):

    if not masked_text or not masked_text.strip():
        return masked_text

    # =====================================
    # 1단계: 마스킹 기호 제거
    # =====================================

    cleaned_text = _remove_masked_symbols(masked_text, mask_info)

    # 전처리 결과 확인용 (UI 붙이면 제거하세요)
    print(f"\n[전처리 결과]\n{cleaned_text}\n")

    # =====================================
    # 2단계: LLM 문장 다듬기
    # =====================================

    user_prompt = f"""
입력: {cleaned_text}
출력:"""

    try:

        response = ollama.chat(
            model="exaone3.5:2.4b",
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt}
            ],
            options={
                "temperature": 0.1,
                "top_p": 0.2
            }
        )

        rewritten = response["message"]["content"].strip()
        rewritten = _strip_markdown_fence(rewritten)

        if not rewritten:
            return cleaned_text

        return rewritten

    except Exception as e:

        print(f"[Rewrite Error] {e}")
        return cleaned_text